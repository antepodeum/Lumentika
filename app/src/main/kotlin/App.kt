@UIComponent
class ProofComponent : Component() {
    val title = prop("Generated by lumentika-ksp")
    val checked = binding(false)
    val change = event<Boolean>()
    val content = slot()
    lateinit var boundControl: ControlHandle
        private set

    override fun view(): Element = ui.column {
        text { title.value }
        boundControl = checkbox { bindValue(checked) }
        content.mount(this)
    }
}

data class ReactiveProof(
    val initialTexts: List<String>,
    val externalUpdateTexts: List<String>,
    val bindingWriteTexts: List<String>,
    val finalBindingValue: Boolean,
    val deliveredEvent: Boolean,
    val derivedExecutions: Int,
    val viewExecutions: Int,
    val componentDisposed: Boolean,
)

data class TaffyLayoutProof(
    val grid: Rect,
    val firstCell: Rect,
    val secondCell: Rect,
)

fun runTaffyLayoutProof(): TaffyLayoutProof {
    val frames = HeadlessFrameScheduler()
    val root =
        UiRoot(
            UiEnvironment(Size(320f, 200f)),
            PlatformServices(frames),
            object : RenderBackend {
                override fun replay(artifact: PaintArtifact) = Unit
            },
        )
    lateinit var first: Element
    lateinit var second: Element
    val grid =
        root.scope.grid {
            style {
                display = Display.GRID
                itemIsTable = false
                itemIsReplaced = false
                boxSizing = BoxSizing.BORDER_BOX
                direction = Direction.LTR
                overflowX = Overflow.CLIP
                overflowY = Overflow.AUTO
                scrollbarWidth = 6.px
                floatValue = FloatLayout.NONE
                clear = Clear.NONE
                position = Position.RELATIVE
                inset = edges(Auto)
                width = 240.px
                height = 120.px
                minWidth = 160.px
                minHeight = 80.px
                maxWidth = 280.px
                maxHeight = 160.px
                aspectRatio = 2f
                margin = edges(4.px)
                padding = edges(6.px)
                border = edges(1.px)
                alignItems = AlignItems.STRETCH
                alignSelf = AlignItems.START
                justifyItems = AlignItems.STRETCH
                justifySelf = AlignItems.START
                alignContent = AlignContent.START
                justifyContent = AlignContent.START
                columnGap = 8.px
                rowGap = 10.px
                textAlign = TextAlign.AUTO
                flexDirection = FlexDirection.ROW
                flexWrap = FlexWrap.WRAP
                flexBasis = Auto
                flexGrow = 0f
                flexShrink = 1f
                gridTemplateColumns =
                    listOf(
                        GridTemplateComponent.Single(GridTrackSizing.fixed(80.px)),
                        GridTemplateComponent.Single(GridTrackSizing.flex(1)),
                    )
                gridTemplateRows =
                    listOf(
                        GridTemplateComponent.Single(GridTrackSizing.fixed(40.px)),
                        GridTemplateComponent.Single(GridTrackSizing.flex(1)),
                    )
                gridAutoColumns = listOf(GridTrackSizing.Auto)
                gridAutoRows = listOf(GridTrackSizing.Auto)
                gridAutoFlow = GridAutoFlow.ROW_DENSE
                gridTemplateAreas = null
                gridTemplateColumnNames = listOf(emptyList(), emptyList(), emptyList())
                gridTemplateRowNames = listOf(emptyList(), emptyList(), emptyList())
                gridRow = GridLine()
                gridColumn = GridLine()
                background = rgb(245, 245, 245)
                opacity = 1f
                zIndex = 1
                visibility = Visibility.VISIBLE
                pointerEvents = PointerEvents.AUTO
                fontSize = 14.sp
                color = rgb(20, 20, 20)
            }
            first = text {
                value = "Grid A"
                style {
                    gridColumn = GridLine(GridPlacement.Line(1), GridPlacement.Line(2))
                    gridRow = GridLine(GridPlacement.Line(1), GridPlacement.Line(2))
                }
            }
            second = text {
                value = "Grid B"
                style {
                    gridColumn = GridLine(GridPlacement.Line(2), GridPlacement.Line(3))
                    gridRow = GridLine(GridPlacement.Line(1), GridPlacement.Span(2))
                }
            }
        }
    root.requestFrame()
    root.frame(1_000_000L)
    val proof = TaffyLayoutProof(grid.geometry, first.geometry, second.geometry)
    check(proof.grid.width == 240f)
    check(proof.grid.height == 120f)
    check(proof.firstCell.width > 0f)
    check(proof.secondCell.x > proof.firstCell.x)
    root.close()
    return proof
}

fun runReactiveProof(): ReactiveProof {
    val frames = HeadlessFrameScheduler()
    val artifacts = arrayOfNulls<PaintArtifact>(1)
    val root =
        UiRoot(
            UiEnvironment(Size(640f, 480f)),
            PlatformServices(frames),
            object : RenderBackend {
                override fun replay(artifact: PaintArtifact) {
                    artifacts[0] = artifact
                }
            },
        )
    val checked = state(false)
    val generatedTitle = state(7)
    var derivedExecutions = 0
    val doubledTitle = derived {
        derivedExecutions++
        generatedTitle.value * 2
    }
    val generatedValue = state(false)
    var generatedEvent: Boolean? = null
    lateinit var proof: ProofComponent
    root.scope.column {
        proofComponent {
            proof = component
            title { "Generated value: ${generatedTitle.value}" }
            bindChecked(generatedValue)
            onChange { generatedEvent = it }
            content { text { value = "Generated slot" } }
        }
        text { "Derived value: ${doubledTitle.value}" }
        text("Lumentika core")
        button {
            value = "Toggle"
            onClick { checked.value = !checked.value }
        }
        checkbox { bindValue(checked) }
        slider { value = 0.5f }
        textField {}
    }
    root.requestFrame()
    root.frame(1_000_000L)
    val initialTexts = artifacts.renderedTexts()
    check("Generated value: 7" in initialTexts)
    check("Derived value: 14" in initialTexts)
    check(doubledTitle.value == 14)
    check(derivedExecutions == 1)
    check("Generated slot" in initialTexts)
    check(!generatedValue.value)

    generatedTitle.value = 9
    generatedValue.value = true
    root.frame(2_000_000L)
    val externalUpdateTexts = artifacts.renderedTexts()
    check(proof.checked.value)
    check(proof.boundControl.semantics.checked == true)
    check("Generated value: 9" in externalUpdateTexts)
    check("Derived value: 18" in externalUpdateTexts)
    check(proof.viewExecutions == 1)

    proof.boundControl.activate()
    generatedTitle.value = 11
    root.frame(3_000_000L)
    val bindingWriteTexts = artifacts.renderedTexts()
    check(!generatedValue.value)
    check(proof.boundControl.semantics.checked == false)
    check("Generated value: 11" in bindingWriteTexts)
    check("Derived value: 22" in bindingWriteTexts)
    check(derivedExecutions == 3)
    check(proof.viewExecutions == 1)

    proof.change.emit(false)
    check(generatedEvent == false)
    root.close()

    proof.change.emit(true)
    proof.checked.value = true
    check(generatedEvent == false)
    check(!generatedValue.value)
    check(proof.componentScope.isDisposed)

    return ReactiveProof(
        initialTexts,
        externalUpdateTexts,
        bindingWriteTexts,
        generatedValue.value,
        requireNotNull(generatedEvent),
        derivedExecutions,
        proof.viewExecutions,
        proof.componentScope.isDisposed,
    )
}

fun main() {
    val proof = runReactiveProof()
    val layout = runTaffyLayoutProof()
    println(
        "Lumentika reactive proof passed: value=${proof.finalBindingValue}, " +
            "event=${proof.deliveredEvent}, derivedExecutions=${proof.derivedExecutions}, " +
            "viewExecutions=${proof.viewExecutions}; " +
            "Taffy layout=${layout.grid.width}x${layout.grid.height}"
    )
}

private fun Array<PaintArtifact?>.renderedTexts(): List<String> =
    requireNotNull(this[0])
        .chunks
        .flatMap { it.commands }
        .filterIsInstance<PaintCommand.DrawText>()
        .map(PaintCommand.DrawText::text)
